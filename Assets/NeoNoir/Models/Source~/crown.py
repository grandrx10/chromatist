# Generates Crown.obj: the Emperor's little crown. Lives in a folder ending
# in ~ so Unity never imports it.
#
#   python crown.py > ../Crown.obj
#
# A ring of flat panels, each a band with a triangular point on top, with
# real thickness. Every face has its own vertices so the creases stay hard.
# Pivot at the middle of the bottom edge, standing up along +Y. It is the
# same all the way round, so Unity's X mirror changes nothing.
#
# About 0.24 across and 0.12 tall: scale it to fit the head.

import math

POINTS = 5            # points around the crown
RADIUS = 0.12         # middle to the outside of the band
BAND = 0.04           # height of the band the points stand on
POINT = 0.08          # height of each point above the band
THICKNESS = 0.012     # measured inward

verts = []
normals = []
faces = []


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def centroid(poly):
    n = len(poly)
    return tuple(sum(p[i] for p in poly) / n for i in range(3))


def at(angle, distance, height):
    return (math.sin(angle) * distance, height, math.cos(angle) * distance)


def face(poly, inside):
    """A flat convex polygon, wound counter-clockwise seen from away from inside."""
    normal = cross(sub(poly[1], poly[0]), sub(poly[2], poly[0]))
    if dot(normal, sub(centroid(poly), inside)) < 0:
        poly = poly[::-1]
        normal = tuple(-c for c in normal)
    length = math.sqrt(dot(normal, normal))
    normals.append(tuple(c / length for c in normal))
    start = len(verts) + 1
    verts.extend(poly)
    faces.append([(start + i, len(normals)) for i in range(len(poly))])


def panel(a0, a1, inner):
    top = BAND + POINT
    sides = []
    for r in (RADIUS, inner):
        left, right = at(a0, r, BAND), at(a1, r, BAND)
        # The apex sits on the chord, not the circle, so the panel stays flat.
        apex = ((left[0] + right[0]) / 2, top, (left[2] + right[2]) / 2)
        sides.append([at(a0, r, 0), left, apex, right, at(a1, r, 0)])
    out, ins = sides
    inside = tuple((x + y) / 2 for x, y in zip(centroid(out), centroid(ins)))

    face(out, inside)
    face(ins, inside)
    face([out[0], out[4], ins[4], ins[0]], inside)  # bottom
    face([out[1], out[2], ins[2], ins[1]], inside)  # left slope
    face([out[2], out[3], ins[3], ins[2]], inside)  # right slope
    face([out[0], out[1], ins[1], ins[0]], inside)  # ends, where panels meet
    face([out[4], out[3], ins[3], ins[4]], inside)


step = 2 * math.pi / POINTS
for i in range(POINTS):
    panel(i * step, (i + 1) * step, RADIUS - THICKNESS)

print("# Crown: a ring of pointed panels, standing up along Y, pivot at the bottom middle.")
print("# Generated by Source~/crown.py -- edit that, not this.")
print("o Crown")
for v in verts:
    print("v %.6f %.6f %.6f" % v)
for n in normals:
    print("vn %.6f %.6f %.6f" % n)
for f in faces:
    print("f " + " ".join("%d//%d" % pair for pair in f))
