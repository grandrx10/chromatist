// Generates HexSphere.obj: a hexagonal barrier sphere made of separate, inset
// panels. Lives in a folder ending in ~ so Unity never imports it.
//
//   node hex_sphere.js [frequency] [inset] > ../HexSphere.obj
//
// frequency  How finely the sphere is divided. Panels = 10 * f^2 + 2, always
//            12 of them pentagons (a sphere cannot be tiled by hexagons alone).
//            3 -> 92 panels, 4 -> 162, 5 -> 252. Default 4.
// inset      Fraction of its size each panel keeps, leaving a gap to its
//            neighbours. 1 is no gap. Default 0.94.
//
// Built as the dual of a geodesic icosphere (a Goldberg polyhedron): every
// geodesic vertex becomes one panel whose corners are the centres of the
// triangles around it.
//
// Each panel is a triangle fan from a centre vertex, with the data the
// NeoNoir/Barrier shader reads packed into UV0:
//
//   u  0 at the panel centre, 1 on its border. Interpolated across a fan
//      triangle it is exactly the fraction of the way to that triangle's
//      outer edge, so a cut on it draws an even-width border.
//   v  A random value per panel, constant across it. Drives the order the
//      panels flicker in.
//
// Normals point straight out from the sphere centre rather than off the flat
// panels, so the fresnel rim is smooth across the whole barrier. Radius 1.

const frequency = Math.max(1, parseInt(process.argv[2] || "4", 10));
const inset = Math.min(1, Math.max(0.1, parseFloat(process.argv[3] || "0.94")));

const add = (a, b) => [a[0] + b[0], a[1] + b[1], a[2] + b[2]];
const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const scale = (a, s) => [a[0] * s, a[1] * s, a[2] * s];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
const cross = (a, b) => [a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0]];
const normalize = (a) => scale(a, 1 / Math.hypot(a[0], a[1], a[2]));

// ---- icosahedron ---------------------------------------------------------

const t = (1 + Math.sqrt(5)) / 2;
const icoVerts = [
    [-1, t, 0], [1, t, 0], [-1, -t, 0], [1, -t, 0],
    [0, -1, t], [0, 1, t], [0, -1, -t], [0, 1, -t],
    [t, 0, -1], [t, 0, 1], [-t, 0, -1], [-t, 0, 1],
].map(normalize);

const icoFaces = [
    [0, 11, 5], [0, 5, 1], [0, 1, 7], [0, 7, 10], [0, 10, 11],
    [1, 5, 9], [5, 11, 4], [11, 10, 2], [10, 7, 6], [7, 1, 8],
    [3, 9, 4], [3, 4, 2], [3, 2, 6], [3, 6, 8], [3, 8, 9],
    [4, 9, 5], [2, 4, 11], [6, 2, 10], [8, 6, 7], [9, 8, 1],
];

// ---- geodesic subdivision ------------------------------------------------

const geoVerts = [];
const geoIndex = new Map();
const geoTris = [];

// Points on shared edges are generated by both faces, so dedupe by position.
function geoVertex(p) {
    const n = normalize(p);
    const key = n.map((c) => c.toFixed(5)).join(",");

    if (!geoIndex.has(key)) {
        geoIndex.set(key, geoVerts.length);
        geoVerts.push(n);
    }

    return geoIndex.get(key);
}

for (const [ia, ib, ic] of icoFaces) {
    const a = icoVerts[ia];
    const ab = scale(sub(icoVerts[ib], a), 1 / frequency);
    const ac = scale(sub(icoVerts[ic], a), 1 / frequency);
    const at = (i, j) => geoVertex(add(a, add(scale(ab, i), scale(ac, j))));

    for (let i = 0; i < frequency; i++) {
        for (let j = 0; i + j < frequency; j++) {
            geoTris.push([at(i, j), at(i + 1, j), at(i, j + 1)]);

            if (i + j < frequency - 1) {
                geoTris.push([at(i + 1, j), at(i + 1, j + 1), at(i, j + 1)]);
            }
        }
    }
}

// ---- dual: one panel per geodesic vertex ---------------------------------

const trisAround = geoVerts.map(() => []);
geoTris.forEach((tri, index) => tri.forEach((v) => trisAround[v].push(index)));

const centroid = (tri) => normalize(add(add(geoVerts[tri[0]], geoVerts[tri[1]]), geoVerts[tri[2]]));

// Deterministic, so regenerating gives the same flicker order.
let seed = 1234567;
const random = () => {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    return seed / 2147483648;
};

const positions = [];
const uvs = [];
const faces = [];
let hexes = 0;
let pentagons = 0;

for (let v = 0; v < geoVerts.length; v++) {
    const axis = geoVerts[v];

    // Order the corners round the panel, counter-clockwise seen from outside.
    const helper = Math.abs(axis[1]) < 0.9 ? [0, 1, 0] : [1, 0, 0];
    const tangent = normalize(cross(helper, axis));
    const bitangent = cross(axis, tangent);

    const corners = trisAround[v]
        .map((index) => centroid(geoTris[index]))
        .map((p) => ({ p, angle: Math.atan2(dot(p, bitangent), dot(p, tangent)) }))
        .sort((x, y) => x.angle - y.angle)
        .map((c) => c.p);

    if (corners.length === 6) hexes++;
    else pentagons++;

    let centre = [0, 0, 0];
    corners.forEach((c) => (centre = add(centre, c)));
    centre = scale(centre, 1 / corners.length);

    const panel = random() * 0.98 + 0.01;
    const first = positions.length + 1;

    positions.push(centre);
    uvs.push([0, panel]);

    for (const corner of corners) {
        positions.push(add(centre, scale(sub(corner, centre), inset)));
        uvs.push([1, panel]);
    }

    for (let i = 0; i < corners.length; i++) {
        const a = first + 1 + i;
        const b = first + 1 + ((i + 1) % corners.length);
        faces.push([first, a, b]);
    }
}

// ---- write ---------------------------------------------------------------

const out = [];
out.push(`# Hex sphere: radius 1, frequency ${frequency}, inset ${inset}, ${hexes} hexagons + ${pentagons} pentagons`);
out.push("# Generated by Source~/hex_sphere.js. UV.x: 0 panel centre, 1 border. UV.y: random per panel.");
out.push("o HexSphere");

const f6 = (x) => x.toFixed(6);
positions.forEach((p) => out.push(`v ${f6(p[0])} ${f6(p[1])} ${f6(p[2])}`));
uvs.forEach((uv) => out.push(`vt ${f6(uv[0])} ${f6(uv[1])}`));
positions.forEach((p) => {
    const n = normalize(p);
    out.push(`vn ${f6(n[0])} ${f6(n[1])} ${f6(n[2])}`);
});

out.push("s 1");
faces.forEach((f) => out.push("f " + f.map((i) => `${i}/${i}/${i}`).join(" ")));

process.stdout.write(out.join("\n") + "\n");
